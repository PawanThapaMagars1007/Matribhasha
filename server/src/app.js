import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import { rateLimit } from 'express-rate-limit';
import mongoose from 'mongoose';
import authRoutes from './routes/auth.js';
import userRoutes from './routes/users.js';
import languageRoutes from './routes/languages.js';
import varietyRoutes from './routes/varieties.js';
import scriptRoutes from './routes/scripts.js';
import characterRoutes from './routes/characters.js';
import practiceRoutes from './routes/practice.js';
import adminLearningRoutes from './routes/adminLearning.js';
import audioRoutes from './routes/audio.js';
import vocabularyRoutes from './routes/vocabulary.js';
import grammarRoutes from './routes/grammar.js';
import sentencePracticeRoutes from './routes/sentencePractice.js';
import userLearningRoutes from './routes/userLearning.js';
import dictionaryRoutes from './routes/dictionary.js';
import adminContentRoutes from './routes/adminContent.js';
import courseRoutes from './routes/courses.js';
import learningActivityRoutes from './routes/learningActivities.js';
import learnerHubRoutes from './routes/learnerHub.js';
import culturalLibraryRoutes from './routes/culturalLibrary.js';
import communityRoutes from './routes/communities.js';
import contributionRoutes from './routes/contributions.js';
import culturalModerationRoutes from './routes/culturalModeration.js';
import discussionRoutes from './routes/discussions.js';
import { errorHandler, notFound } from './middleware/errors.js';
import { csrfProtection, rejectStructuredQueryValues, rejectUnsafeBodyKeys, requestContext } from './middleware/requestSecurity.js';

export function createApp(config) {
  const app = express();
  app.disable('x-powered-by');
  app.set('trust proxy', config.proxyHops);
  app.set('query parser', 'simple');
  app.use(requestContext);
  app.use(helmet({ referrerPolicy: { policy: 'strict-origin-when-cross-origin' } }));
  app.use(cors({ origin: (origin, callback) => callback(null, !origin || config.clientOrigins.includes(origin)), credentials: true, methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'], allowedHeaders: ['Content-Type', 'Authorization', 'X-CSRF-Token', 'X-Recording-Consent', 'X-Audio-Attribution', 'X-Audio-Duration-Seconds', 'X-Speaker-Label', 'X-Audio-Source', 'X-Media-Title', 'X-Media-Description', 'X-Language-Id', 'X-Variety-Id', 'X-Access-Level', 'X-Sensitivity', 'X-Request-Id'] }));
  app.use(express.json({ limit: '1mb', strict: true }));
  app.use(rejectStructuredQueryValues);
  app.use(rejectUnsafeBodyKeys);
  app.use(csrfProtection(config));
  app.use('/api', rateLimit({ windowMs: 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false, message: { message: 'Too many requests. Please try again shortly.' } }));
  app.use('/api/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: 'draft-7', legacyHeaders: false, message: { message: 'Too many sign-in requests. Please wait before trying again.' } }));

  const live = (_req, res) => res.json({ status: 'ok' });
  const ready = (_req, res) => {
    const databaseReady = mongoose.connection.readyState === 1;
    return res.status(databaseReady ? 200 : 503).json({ status: databaseReady ? 'ready' : 'not_ready', dependencies: { database: databaseReady ? 'available' : 'unavailable' } });
  };
  app.get('/health', live);
  app.get('/health/ready', ready);
  app.get('/api/health', live);
  app.get('/api/health/ready', ready);

  app.use('/api/auth', authRoutes);
  app.use('/api/users', userRoutes);
  app.use('/api/languages', languageRoutes);
  app.use('/api/varieties', varietyRoutes);
  app.use('/api/scripts', scriptRoutes);
  app.use('/api', characterRoutes);
  app.use('/api/practice', practiceRoutes);
  app.use('/api/admin/learning', adminLearningRoutes);
  app.use('/api/admin/content', adminContentRoutes);
  app.use('/api/audio', audioRoutes);
  app.use('/api/users/learning', userLearningRoutes);
  app.use('/api', courseRoutes);
  app.use('/api/users', learnerHubRoutes);
  app.use('/api', learningActivityRoutes);
  app.use('/api', culturalLibraryRoutes);
  app.use('/api', communityRoutes);
  app.use('/api', contributionRoutes);
  app.use('/api', culturalModerationRoutes);
  app.use('/api', discussionRoutes);
  app.use('/api/sentence-practice', sentencePracticeRoutes);
  app.use('/api', vocabularyRoutes);
  app.use('/api', dictionaryRoutes);
  app.use('/api', grammarRoutes);
  app.use(notFound);
  app.use(errorHandler);
  return app;
}
